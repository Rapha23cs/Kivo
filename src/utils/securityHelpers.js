function rotr(x, n) {
  return (x >>> n) | (x << (32 - n));
}

export function sha256HexFallback(message) {
  const bytes = typeof TextEncoder !== 'undefined'
    ? new TextEncoder().encode(String(message))
    : Array.from(unescape(encodeURIComponent(String(message))), (c) => c.charCodeAt(0));

  const bitLen = bytes.length * 8;
  const withOneLen = bytes.length + 1;
  const paddedLen = Math.ceil((withOneLen + 8) / 64) * 64;
  const padded = new Uint8Array(paddedLen);
  padded.set(bytes);
  padded[bytes.length] = 0x80;

  const view = new DataView(padded.buffer);
  view.setUint32(paddedLen - 8, Math.floor(bitLen / 0x100000000), false);
  view.setUint32(paddedLen - 4, bitLen >>> 0, false);

  const H = [
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
    0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19
  ];
  const w = new Uint32Array(64);

  for (let offset = 0; offset < paddedLen; offset += 64) {
    for (let i = 0; i < 16; i += 1) {
      w[i] = view.getUint32(offset + i * 4, false);
    }
    for (let i = 16; i < 64; i += 1) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }

    let [a, b, c, d, e, f, g, h] = H;
    for (let i = 0; i < 64; i += 1) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const temp1 = (h + S1 + ch + SHA256_K[i] + w[i]) >>> 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (S0 + maj) >>> 0;

      h = g;
      g = f;
      f = e;
      e = (d + temp1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (temp1 + temp2) >>> 0;
    }

    H[0] = (H[0] + a) >>> 0;
    H[1] = (H[1] + b) >>> 0;
    H[2] = (H[2] + c) >>> 0;
    H[3] = (H[3] + d) >>> 0;
    H[4] = (H[4] + e) >>> 0;
    H[5] = (H[5] + f) >>> 0;
    H[6] = (H[6] + g) >>> 0;
    H[7] = (H[7] + h) >>> 0;
  }

  return H.map((val) => val.toString(16).padStart(8, '0')).join('');
}

export function getUserPinSalt(userId = '') {
  const cleanUid = String(userId || '').trim();
  return cleanUid ? `kivo-session-pin-v2:${cleanUid}` : 'kivo-session-pin-v1';
}

export function generateSecureUuid() {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  if (typeof crypto !== 'undefined' && typeof crypto.getRandomValues === 'function') {
    const bytes = new Uint8Array(16);
    crypto.getRandomValues(bytes);
    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
  }
  throw new Error('Ambiente sem suporte a gerador criptográfico seguro (Web Crypto API).');
}

export async function hashPinSha256(pin, salt = 'kivo-session-pin-v1') {
  const clean = String(pin || '').trim();
  if (!clean) return '';
  const payload = `${salt}:${clean}`;
  if (typeof crypto !== 'undefined' && crypto.subtle && typeof TextEncoder !== 'undefined') {
    const data = new TextEncoder().encode(payload);
    const digest = await crypto.subtle.digest('SHA-256', data);
    return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, '0')).join('');
  }
  // Fallback SHA-256 criptográfico caso crypto.subtle esteja indisponível (ex.: HTTP local sem localhost)
  return sha256HexFallback(payload);
}

export function validateStrongPassword(password = '') {
  const pwd = String(password || '');
  const minLength = pwd.length >= 8;
  const hasLetter = /[A-Za-z]/.test(pwd);
  const hasNumberOrSymbol = /[0-9!@#$%^&*(),.?":{}|<>_\-+=]/.test(pwd);
  return {
    valid: minLength && hasLetter && hasNumberOrSymbol,
    minLength,
    hasLetter,
    hasNumberOrSymbol
  };
}

export function getPasswordScore(password = '') {
  const pwd = String(password || '');
  return (
    (pwd.length >= 8 ? 1 : 0) +
    (pwd.length >= 10 ? 1 : 0) +
    (/[A-Z]/.test(pwd) && /[a-z]/.test(pwd) ? 1 : 0) +
    (/[0-9!@#$%^&*(),.?":{}|<>_\-+=]/.test(pwd) ? 1 : 0)
  );
}
